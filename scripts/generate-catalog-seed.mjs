// Writes the curated catalog seed as an idempotent SQL migration.
// Run with: npm run catalog:seed   (then apply the migration as usual)
import { writeFile } from "node:fs/promises";
import path from "node:path";
import { DOMAINS } from "./catalog-seed-data.mjs";

// Must match topicKey() in src/lib/utils.ts.
export function nameKey(s) {
  return s
    .toLowerCase()
    .normalize("NFKD")
    .replace(/[^\p{Letter}\p{Number}]+/gu, "-")
    .replace(/^-+|-+$/g, "")
    .slice(0, 120);
}

const q = (s) => (s === null || s === undefined ? "null" : `'${String(s).replace(/'/g, "''")}'`);
const arr = (xs) => `array[${xs.map(q).join(", ")}]::text[]`;

export function buildSeedSql(domains = DOMAINS) {
  const lines = [
    "-- GENERATED by scripts/generate-catalog-seed.mjs — edit scripts/catalog-seed-data.mjs instead.",
    "-- Curated starting points for the knowledge catalog. Safe to re-run (on conflict do nothing).",
    "",
  ];
  for (const d of domains) {
    const dKey = nameKey(d.name);
    const aliases = d.aliases ?? [];
    lines.push(
      `insert into public.knowledge_nodes (path, name, name_key, aliases, alias_keys, description, kind, learning_pattern, icon, origin, status) values (${q(dKey)}, ${q(d.name)}, ${q(dKey)}, ${arr(aliases)}, ${arr(aliases.map(nameKey))}, ${q(d.description)}, 'domain', ${q(d.pattern)}, ${q(d.icon)}, 'curated', 'verified') on conflict do nothing;`,
    );
    for (const entry of d.disciplines) {
      const [name, opts = {}] = Array.isArray(entry) ? entry : [entry, {}];
      const key = nameKey(name);
      const al = opts.aliases ?? [];
      lines.push(
        `insert into public.knowledge_nodes (parent_id, path, name, name_key, aliases, alias_keys, kind, learning_pattern, origin, status) select id, ${q(`${dKey}/${key}`)}, ${q(name)}, ${q(key)}, ${arr(al)}, ${arr(al.map(nameKey))}, 'discipline', ${q(opts.pattern ?? d.pattern)}, 'curated', 'verified' from public.knowledge_nodes where path = ${q(dKey)} on conflict do nothing;`,
      );
    }
    lines.push("");
  }
  return lines.join("\n");
}

if (process.argv[1]?.endsWith("generate-catalog-seed.mjs")) {
  const out = path.resolve(import.meta.dirname, "..", "db", "migrations", "20261024000200_catalog_seed.sql");
  await writeFile(out, buildSeedSql());
  console.log(`Wrote ${out}`);
}
