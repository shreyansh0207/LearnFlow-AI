/** AI-prioritised revision plan, limited to the learner's real topics. */
export function RevisionPlanCard() {
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const [plan, setPlan] = useState<RevisionPlan | null>(null);
  return (
    <Card className="space-y-3">
      <div className="flex flex-wrap items-center justify-between gap-2">
        <CardTitle className="flex items-center gap-2">
          <Sparkles aria-hidden className="size-4 text-accent" /> What should I revise?
        </CardTitle>
        <Button
          size="sm"
          variant="secondary"
          disabled={busy}
          onClick={async () => {
            setBusy(true);
            setError(null);
            const r = await call<{ plan: RevisionPlan }>("/api/revision/plan", { method: "POST" });
            setBusy(false);
            if (r.ok) setPlan(r.data.plan);
            else setError(r.error);
          }}
        >
          {busy && <LoaderCircle aria-hidden className="size-4 animate-spin" />}
          {plan ? "Refresh plan" : "Get an AI revision plan"}
        </Button>
      </div>
      <p className="text-xs text-muted">Built only from your mastery, quiz results and due cards. Topic titles and scores are shared with Gemini; notes and personal details are not.</p>
      {error && (
        <Alert kind="error">
          <span className="inline-flex items-center gap-1">
            <CircleAlert aria-hidden className="size-3.5" /> {error}
          </span>
        </Alert>
      )}
      {plan && (
        <div className="space-y-2" aria-live="polite">
          <p className="text-sm">{plan.summary}</p>
          <ol className="space-y-2">
            {plan.items.map((i, idx) => (
              <li key={i.topic} className={cn("rounded-xl border border-border p-3 text-sm")}>
                <p className="font-medium">
                  {idx + 1}. {i.topic} <span className="text-xs font-normal text-muted">· ~{i.minutes} min</span>
                </p>
                <p className="text-muted">{ACTIVITY_LABEL[i.activity]} — {i.reason}</p>
              </li>
            ))}
          </ol>
          <Badge tone="accent">AI-generated suggestion</Badge>{" "}
          <Link href="/progress" className="text-xs text-primary">
            See your full progress →
          </Link>
        </div>
      )}
    </Card>
  );
}
